"""Generate work/scripts/PROBES.md: what every tracked Frida script is, and whether it is safe.

The classification is mechanical, from the script's own source:
    OBSERVER   attaches and reads; never writes to the game process
    WRITER     writes memory, replaces a function or patches code. The runtime prototypes of the
               scaling fixes are all writers: each was the readable, iterable version of a fix
               BEFORE it was baked into work/patches/patches.yaml
A writer carries addresses that were right for the build it was written against. A later bake
moves code caves; a stale offset crashes the game. Read a writer, do not run it as is.

    py work\\scripts\\gen_probe_catalog.py           rewrite PROBES.md
    py work\\scripts\\gen_probe_catalog.py --check   exit 1 if PROBES.md is out of date

test_probe_catalog.py runs the check, so a probe cannot be added or reclassified without the
catalogue following.
"""

from __future__ import annotations

import re
import subprocess
import sys
from pathlib import Path

_SCRIPTS = Path(__file__).resolve().parent
CATALOG = _SCRIPTS / "PROBES.md"

WRITE_RX = re.compile(
    r"\.write(?:U|S)?(?:8|16|32|64)\s*\(|\.write(?:Pointer|ByteArray|Float|Double|"
    r"Utf8String|AnsiString|Utf16String|Int|UInt|Short|UShort|Long|ULong)\s*\(|"
    r"Interceptor\.replace\s*\(|Memory\.patchCode\s*\(|Memory\.protect\s*\(|Memory\.copy\s*\(|"
    r"\.putBytes\s*\(|new\s+X86Writer\s*\(")
#: Loaded WITH a probe rather than run as one: the laws prelude, helpers, and pre-scripts that
#: only set a variable for the hook that follows (aivis_mode_filter.js selects the WRITING mode
#: of hook_aivis_proto.js, so it must not sit in the read-only list).
SHARED = ("scaling_laws.js", "frida_common.js", "frida_log_append.js", "aivis_mode_filter.js")


def tracked_js(scripts: Path = _SCRIPTS) -> list:
    """The tracked .js files of work/scripts, minus `_`-prefixed scratch (never part of the
    source release). In a tree whose git does not track them (a source zip, or the export
    before its first commit) every .js present is part of the release, so the directory
    listing is the answer."""
    names = []
    try:
        p = subprocess.run(["git", "-C", str(scripts), "ls-files", "-z", "--", "*.js"],
                           capture_output=True, timeout=60)
        if p.returncode == 0:
            names = [n for n in p.stdout.decode("utf-8", "replace").split("\0")
                     if n and "/" not in n]
    except (OSError, subprocess.TimeoutExpired):
        pass
    if not names:
        names = [p.name for p in scripts.glob("*.js")]
    return sorted(n for n in names if not n.startswith("_"))


def describe(text: str) -> str:
    """The script's own first sentence: the leading comment lines, joined, cut at the first
    full stop or blank comment line."""
    out = []
    for line in text.splitlines():
        s = line.strip()
        if not s or s in ('"use strict";', "'use strict';"):
            if out:
                break
            continue
        if s.startswith("//"):
            body = s.lstrip("/").strip()
            if not body or set(body) <= set("-=*~ "):
                if out:
                    break
                continue
            if body.upper().startswith("HISTORICAL PROTOTYPE"):
                return describe_after_banner(text)
            out.append(body)
            if body.endswith((".", ":")) or len(" ".join(out)) > 200:
                break
        elif s.startswith("/*") or s.startswith("*"):
            body = s.strip("/* ").strip()
            if body:
                out.append(body)
                if body.endswith(".") or len(" ".join(out)) > 200:
                    break
        else:
            break
    d = " ".join(out).replace("|", "/").strip()
    return (d[:217] + "...") if len(d) > 220 else d


def describe_after_banner(text: str) -> str:
    lines = text.splitlines()
    i = 0
    while i < len(lines) and (lines[i].strip().startswith("//") or not lines[i].strip()):
        if not lines[i].strip() and i > 0:
            break
        i += 1
    return describe("\n".join(lines[i:]))


def classify(name: str, text: str) -> str:
    if name in SHARED:
        return "shared"
    return "writer" if WRITE_RX.search(text) else "observer"


def build(scripts: Path = _SCRIPTS) -> str:
    rows = {"shared": [], "observer": [], "writer": []}
    for name in tracked_js(scripts):
        text = (scripts / name).read_text(encoding="utf-8", errors="replace")
        rows[classify(name, text)].append((name, describe(text)))
    out = [
        "# Frida scripts in this folder", "",
        "Generated by `gen_probe_catalog.py` from the scripts themselves; do not edit by hand.",
        "Run one with `work\\run-frida.bat <script>` or, at a chosen resolution,",
        "`work\\run-frida-at-res.bat <script> <W> <H>`. For a vanilla baseline use",
        "`work\\run-frida-pristine.bat` (the unpatched PRACX binary) or",
        "`work\\run-frida-truevanilla.bat` (the un-PRACX'd game): never measure \"native\" on the",
        "patched exe at a low resolution. The pristine launcher runs `terranx_pristine.exe`, a",
        "copy of the patcher's `.bak` that you place in the game folder. Read the frida-tracing",
        "skill first: a badly placed attach crashes the game. Probes that dump buffers write",
        "captured game pixels under `work\\_*\\`; those folders are git-ignored and must stay so.",
        "",
        f"## Shared ({len(rows['shared'])})", "",
        "Loaded together with a probe, not run as one.", "",
        "| Script | What it is |", "|---|---|",
    ]
    out += [f"| `{n}` | {d} |" for n, d in rows["shared"]]
    out += [
        "", f"## Observers ({len(rows['observer'])})", "",
        "Attach and read. They do not write to the game process.", "",
        "| Script | What it measures |", "|---|---|",
    ]
    out += [f"| `{n}` | {d} |" for n, d in rows["observer"]]
    out += [
        "", f"## Writers: prototypes and runtime fixes ({len(rows['writer'])})", "",
        "**Read these; do not run them as they are.** Each writes to the game process at",
        "addresses that were right for the build it was written against. A later bake moves code",
        "caves, and a stale offset crashes the game. Most are the readable, iterable version of a",
        "fix that now ships as a baked patch group in `work/patches/patches.yaml`; the assemblers",
        "and tests that cite them took their tables from here.", "",
        "| Script | What it prototypes or changes |", "|---|---|",
    ]
    out += [f"| `{n}` | {d} |" for n, d in rows["writer"]]
    return "\n".join(out) + "\n"


def main(argv=None) -> int:
    argv = sys.argv[1:] if argv is None else argv
    text = build()
    if "--check" in argv:
        have = CATALOG.read_text(encoding="utf-8").replace("\r\n", "\n") if CATALOG.is_file() else ""
        if have != text:
            print("PROBES.md is out of date: run gen_probe_catalog.py")
            return 1
        print("PROBES.md is current")
        return 0
    CATALOG.write_bytes(text.encode("utf-8"))
    print(f"wrote {CATALOG}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
