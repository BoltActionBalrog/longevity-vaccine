"""Regenerate thinker_data.py from Thinker's public git history and the pinned release's files.

    py gen_thinker_data.py [--check]

Reads (never writes) the workspace references:
  refs/thinker                   git clone of github.com/induktio/thinker (tags v0.6 .. v5.5)
  refs/thinker-release/v<pin>/   the pinned release's 28 files, as its GitHub zip holds them
Writes work/scripts/thinker_data.py (or, with --check, exits 1 if it would change).

What it compiles (decision MD-SRC, user 2026-11-14: small comparison data may ship in the
installer; Thinker's builds never do):
  * KNOWN_KEYS: every setting name the pinned Thinker's option_handler accepts (MATCH("...")).
  * STOCK_VALUES: for every tag, the values its stock docs/thinker.ini sets, as Thinker reads them.
  * PIN: the pinned release's tag, asset, zip size and sha256, dll sha256, and per-path file table.
"""
from __future__ import annotations

import argparse
import hashlib
import re
import subprocess
import sys
from pathlib import Path

_HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(_HERE))
import thinker_ini  # noqa: E402

ROOT = _HERE.parent.parent
REFS = ROOT / "refs"          # gitignored; in a worktree pass --refs pointing at the main checkout's refs folder
OUT = _HERE / "thinker_data.py"

# The pinned release. The zip's size and sha256 are GitHub's published asset digest, verified on
# 2026-11-14 by downloading Thinker_v5.5.zip (with the user's permission): its 28 files equal
# refs/thinker-release/v5.5 byte for byte, at the zip's root.
PIN_VERSION = "5.5.0"
PIN_TAG = "v5.5"
PIN_ASSET = "Thinker_v5.5.zip"
PIN_ZIP_SIZE = 755617
PIN_ZIP_SHA256 = "d8d30b28295fbe1d8870192165eb34af6e18ca9cb937838620649db057165fa9"


def _git(*args) -> bytes:
    return subprocess.run(["git", "-C", str(REFS / "thinker"), *args], check=True, capture_output=True).stdout


def _tags() -> list:
    tags = _git("tag").decode().split()
    return sorted((t for t in tags if re.fullmatch(r"v\d+\.\d+(\.\d+)?", t)),
                  key=lambda t: tuple(int(x) for x in t[1:].split(".")))


def _stock_values(tag: str) -> dict:
    try:
        data = _git("show", f"{tag}:docs/thinker.ini")
    except subprocess.CalledProcessError:
        return {}
    values = {}
    for pl in thinker_ini.scan(data):
        for r in pl.reads:
            if r.kind in ("key", "cont") and r.section == thinker_ini.SECTION:
                values.setdefault(r.name.decode("latin-1"), []).append(r.value.decode("latin-1"))
    return values


def _known(tag: str) -> list:
    src = _git("grep", "-h", "-o", "-E", r'MATCH\("[A-Za-z0-9_]+"\)', tag, "--", "src").decode()
    return sorted(set(re.findall(r'MATCH\("([A-Za-z0-9_]+)"\)', src)))


def _files(release: Path) -> dict:
    return {p.relative_to(release).as_posix(): hashlib.sha256(p.read_bytes()).hexdigest()
            for p in sorted(release.rglob("*")) if p.is_file()}


def render() -> str:
    release = REFS / "thinker-release" / PIN_TAG
    files = _files(release)
    dll = (release / "thinker.dll").read_bytes()
    pe = int.from_bytes(dll[0x3C:0x40], "little")
    stamp = int.from_bytes(dll[pe + 8:pe + 12], "little")
    size = int.from_bytes(dll[pe + 0x50:pe + 0x54], "little")
    stock = {t: _stock_values(t) for t in _tags()}
    stock = {t: v for t, v in stock.items() if v}
    lines = [
        '"""GENERATED by gen_thinker_data.py from Thinker\'s public git history and the pinned release.',
        'Do not edit by hand: run `py gen_thinker_data.py`."""',
        "",
        f"PIN_VERSION = {PIN_VERSION!r}",
        f"PIN_TAG = {PIN_TAG!r}",
        f"PIN_ASSET = {PIN_ASSET!r}",
        f"PIN_ZIP_SIZE = {PIN_ZIP_SIZE}",
        f"PIN_ZIP_SHA256 = {PIN_ZIP_SHA256!r}",
        f"PIN_DLL_SHA256 = {files['thinker.dll']!r}",
        f"PIN_DLL_STAMP = {stamp:#x}          # PE TimeDateStamp: the game's own pin test",
        f"PIN_DLL_IMAGE_SIZE = {size:#x}     # PE SizeOfImage",
        "PIN_DROPBOX = ''            # a development-build pin's own Dropbox path (section 9); '' for GitHub",
        "PIN_RLKEY = ''",
        "",
        "# dll sha256s of Thinker builds THIS release's exe is known not to start with (thinker_overlap.py,",
        "# run by the release pipeline); unioned with the manifest's thinker.fatal for this version only",
        "FATAL = frozenset()",
        "",
        "# path (as in the release zip) -> sha256",
        "PIN_FILES = {",
        *[f"    {k!r}: {v!r}," for k, v in files.items()],
        "}",
        "",
        "# every setting name the pinned Thinker accepts (src/main.cpp option_handler, MATCH)",
        "KNOWN_KEYS = frozenset({",
        *[f"    {k!r}," for k in _known(PIN_TAG)],
        "})",
        "",
        "# tag -> {setting: [values]}: what each release's stock thinker.ini sets (decision MD)",
        "STOCK_VALUES = {",
    ]
    for tag, vals in stock.items():
        lines.append(f"    {tag!r}: {{")
        lines.extend(f"        {k!r}: {v!r}," for k, v in sorted(vals.items()))
        lines.append("    },")
    lines += ["}", ""]
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="exit 1 if thinker_data.py is out of date")
    ap.add_argument("--refs", type=Path, default=None, help="the refs folder (default: <repo>/refs)")
    a = ap.parse_args()
    global REFS
    if a.refs:
        REFS = a.refs
    if not (REFS / "thinker").is_dir() or not (REFS / "thinker-release" / PIN_TAG).is_dir():
        print(f"missing {REFS}/thinker or {REFS}/thinker-release/{PIN_TAG}")
        return 2
    text = render()
    if a.check:
        cur = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if cur != text:
            print("thinker_data.py is out of date: run py gen_thinker_data.py")
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.name} ({len(text)} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
