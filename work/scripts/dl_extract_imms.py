#!/usr/bin/env python
"""Extract the Datalinks proto's patch tables (hook_dl_scale_proto.js v12l) into Python for the bake.
ONE-SHOT, kept as the record of how dl_imms_gen.py was produced from the runtime prototype
hook_dl_scale_proto.js (a historical prototype: see PROBES.md). Its output is committed; run it
from the work\\ folder only if the prototype's tables change.
Parses the add()/raw() rows + FRAME_SITES + font-push loops textually (the rows are uniform, authored
data).  Emits scripts/dl_imms_gen.py with:
  IMMS        = [(site, off, width, kind, a, b, tech, label)]  width 1|4; kind in KINDS
  FRAME_SITES = [(va, set, kind)]  kind HF|DF|HC
  FONT_PUSH   = [va...]
Kinds: HD s(a)-s(b) | MUL2 2*s(a) | MUL2NEG -2*s(a) | MUL3 3*s(a) | BIAS1 s(a)-s(b)+1 |
       NUMG g | DEN16 16 | FLOAT f32(a)*g/16 | VEH min(48, fl((a+16)g/16)-16).
BOT = s(3)+1 -> BIAS1(3,0); TOPD = -(s(25)-s(3)-1) = s(3)-s(25)+1 -> BIAS1(3,25).
"""
import re
import struct

src = open('scripts/hook_dl_scale_proto.js', encoding='utf-8').read()

TECH_LO, TECH_HI = 0x496BB0, 0x49BD00


def parse_fn(t):
    t = t.strip()
    for pat, k in ((r'^S\(([^)]+)\)$', 'S'), (r'^SD\(([^)]+)\)$', 'SD'), (r'^NEG\(([^)]+)\)$', 'NEG'),
                   (r'^S2\(([^)]+)\)$', 'S2'), (r'^NEG2\(([^)]+)\)$', 'NEG2'), (r'^S3\(([^)]+)\)$', 'S3'),
                   (r'^FLOAT\(([^)]+)\)$', 'FLOAT'), (r'^VEH\(([^)]+)\)$', 'VEH')):
        m = re.match(pat, t)
        if not m:
            continue
        if k == 'S':
            return ('HD', int(m.group(1), 0), 0)
        if k == 'SD':
            a, b = [int(x.strip(), 0) for x in m.group(1).split(',')]
            return ('HD', a, b)
        if k == 'NEG':
            return ('HD', 0, int(m.group(1), 0))
        if k == 'S2':
            return ('MUL2', int(m.group(1), 0), 0)
        if k == 'NEG2':
            return ('MUL2NEG', int(m.group(1), 0), 0)
        if k == 'S3':
            return ('MUL3', int(m.group(1), 0), 0)
        if k == 'FLOAT':
            return ('FLOAT', struct.unpack('<I', struct.pack('<f', float(m.group(1))))[0], 0)
        if k == 'VEH':
            return ('VEH', int(m.group(1), 0), 0)
    if t == 'NUMG()':
        return ('NUMG', 0, 0)
    if t == 'DEN16()':
        return ('DEN16', 0, 0)
    if t == 'BOT':
        return ('BIAS1', 3, 0)
    if t == 'TOPD':
        return ('BIAS1', 3, 25)
    return None


imms, unparsed = [], []
src_active = "\n".join(ln for ln in src.split("\n") if not ln.lstrip().startswith("//"))
rx = re.compile(r"add\((0x[0-9A-Fa-f]+),\s*(\d+),\s*('f'|\d+),\s*([A-Za-z0-9_]+(?:\([^)]*\))?),\s*\"(.*?)\"\)")
for m in rx.finditer(src_active):
    site = int(m.group(1), 16)
    off = int(m.group(2))
    wtxt = m.group(3)
    w = 4 if wtxt == "'f'" else int(wtxt)
    fn = parse_fn(m.group(4))
    if fn is None:
        unparsed.append((hex(site), m.group(4), m.group(5)))
        continue
    kind, a, b = fn
    if wtxt == "'f'":
        assert kind == 'FLOAT', (hex(site), m.group(4))
    if kind == 'FLOAT':
        assert wtxt == "'f'", (hex(site), m.group(4))
    tech = 1 if TECH_LO <= site < TECH_HI else 0
    imms.append((site, off, w, kind, a, b, tech, m.group(5)))

# loop-generated TS inset adds: for (const a of [..]) add(a, 2, 1, S(n), "..")
rx2 = re.compile(r"for \(const a of \[([0-9xA-Fa-f, ]+)\]\) add\(a,\s*(\d+),\s*(\d+),\s*(S\([^)]+\)),\s*\"([^\"]+)")
for m in rx2.finditer(src):
    kind, a, b = parse_fn(m.group(4))
    for adr in m.group(1).split(','):
        site = int(adr.strip(), 16)
        imms.append((site, int(m.group(2)), int(m.group(3)), kind, a, b,
                     1 if TECH_LO <= site < TECH_HI else 0, m.group(5)))

imms.sort()
for i in range(1, len(imms)):
    assert (imms[i][0], imms[i][1]) != (imms[i - 1][0], imms[i - 1][1]), hex(imms[i][0])

fsm = re.search(r"const FRAME_SITES = \[(.*?)\n  \];", src, re.S)
fs = [(int(m.group(1), 16), m.group(2), m.group(3))
      for m in re.finditer(r"\[(0x[0-9A-Fa-f]+),\s*\"([^\"]+)\",\s*\"(HF|DF|HC)\"\]", fsm.group(1))]

fpm = re.search(r"for \(const a of \[([0-9xA-Fa-f, ]+)\]\)\s*\n?\s*raw\(a, \[0x68", src)
FONT_PUSH = [int(x.strip(), 16) for x in fpm.group(1).split(',')]

out = ["# GENERATED by dl_extract_imms.py from hook_dl_scale_proto.js v12l -- do not edit by hand.",
       f"TECH_LO, TECH_HI = {hex(TECH_LO)}, {hex(TECH_HI)}",
       "IMMS = ["]
for r in imms:
    out.append(f"    (0x{r[0]:06X}, {r[1]}, {r[2]}, '{r[3]}', {r[4]:#x}, {r[5]:#x}, {r[6]}, {r[7]!r}),")
out.append("]")
out.append("FRAME_SITES = [")
for v, nm, k in fs:
    out.append(f"    (0x{v:06X}, {nm!r}, '{k}'),")
out.append("]")
out.append("FONT_PUSH = [" + ", ".join(hex(x) for x in FONT_PUSH) + "]")
open('scripts/dl_imms_gen.py', 'w', encoding='utf-8', newline='\n').write("\n".join(out) + "\n")
print("imms:", len(imms), "tech:", sum(1 for r in imms if r[6]),
      "float:", sum(1 for r in imms if r[3] == 'FLOAT'),
      "kinds:", sorted({r[3] for r in imms}),
      "| frame sites:", len(fs), "| font pushes:", len(FONT_PUSH))
print("tech NUMG/DEN16 rows:", [hex(r[0]) for r in imms if r[6] and r[3] in ('NUMG', 'DEN16')])
print("UNPARSED:", unparsed if unparsed else "none")
